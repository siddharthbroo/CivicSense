package com.civicsense.complaint.entity;

import com.civicsense.user.entity.User;
import com.civicsense.complaint.entity.cluster.ComplaintCluster;
import com.civicsense.complaint.entity.geo.AdministrativeWard;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;
import java.util.UUID;

@Entity
@Table(name = "complaints")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class Complaint {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /*
     * Citizen who submitted the complaint.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /*
     * Optional title.
     *
     * Generated by the AI/classification layer.
     */
    @Column(length = 150)
    private String title;

    /*
     * Main complaint submitted by the citizen.
     */
    @Column(nullable = false, columnDefinition = "TEXT")
    private String description;

    /*
     * Complaint category.
     */
    @Column(length = 50)
    private String category;

    /*
     * PRIMARY Incident Location: Citizen-confirmed map pin coordinates.
     */
    @Column(nullable = false)
    private Double latitude;

    @Column(nullable = false)
    private Double longitude;

    /*
     * Optional device GPS coordinates at submission time.
     * Used only for suggestion/telemetry; never overrides confirmed pin.
     */
    @Column(name = "device_latitude")
    private Double deviceLatitude;

    @Column(name = "device_longitude")
    private Double deviceLongitude;

    /*
     * Source of confirmed pin (e.g. MAP_PIN, DEVICE_GPS_SUGGESTED, MANUAL).
     */
    @Column(name = "location_source", length = 50)
    private String locationSource;

    /*
     * Accuracy in meters if provided by browser/device.
     */
    @Column(name = "location_accuracy")
    private Double locationAccuracy;

    /*
     * Optional address or landmark provided by the citizen.
     */
    @Column(length = 500)
    private String address;

    /*
     * Cluster to which this complaint belongs.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "cluster_id")
    private ComplaintCluster cluster;

    /*
     * Administrative Ward to which this complaint resolves (Delhi NCR Zone -> Ward).
     * Resolved deterministically from the confirmed incident map pin.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "ward_id")
    private AdministrativeWard ward;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private ComplaintStatus status = ComplaintStatus.SUBMITTED;

    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(nullable = false)
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        createdAt = now;
        updatedAt = now;
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }
}